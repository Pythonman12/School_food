@OptIn(ExperimentalLayoutApi::class)
@Composable
fun AllergySettingsDialog(
    userAllergies: Set<Int>,
    onToggleAllergy: (allergenCode: Int, enabled: Boolean) -> Unit,
    onDismiss: () -> Unit
) {
    AlertDialog(
        onDismissRequest = onDismiss,
        title = {
            Column {
                Text(
                    text = "나의 알레르기 설정",
                    style = MaterialTheme.typography.titleLarge,
                    fontWeight = FontWeight.Bold
                )
                Spacer(modifier = Modifier.height(4.dp))
                Text(
                    text = "해당하는 알레르기 유발 식품을 선택하시면 식단에서 눈에 띄게 경고 표시해 드립니다.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
        },
        text = {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .verticalScroll(rememberScrollState())
                    .testTag("allergy_settings_list")
            ) {
                FlowRow(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    verticalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    Allergen.ALL_ALLERGENS.forEach { allergen ->
                        val isSelected = userAllergies.contains(allergen.code)
                        FilterChip(
                            selected = isSelected,
                            onClick = { onToggleAllergy(allergen.code, !isSelected) },
                            label = {
                                Text(
                                    text = "${allergen.emoji} ${allergen.name}",
                                    style = MaterialTheme.typography.labelMedium.copy(fontSize = 13.sp)
                                )
                            },
                            leadingIcon = if (isSelected) {
                                {
                                    Icon(
                                        imageVector = Icons.Default.Check,
                                        contentDescription = null,
                                        modifier = Modifier.size(16.dp)
                                    )
                                }
                            } else null,
                            colors = FilterChipDefaults.filterChipColors(
                                selectedContainerColor = MaterialTheme.colorScheme.errorContainer,
                                selectedLabelColor = MaterialTheme.colorScheme.onErrorContainer
                            ),
                            shape = RoundedCornerShape(10.dp)
                        )
                    }
                }
            }
        },
        confirmButton = {
            Button(onClick = onDismiss) {
                Text("완료")
            }
        }
    )
}
